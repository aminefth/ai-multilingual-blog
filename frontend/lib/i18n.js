// Translation function
export function t(key, locale = defaultLocale, params = {}) {
  const keys = key.split('.');
  let value = translations[locale];

  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k];
    } else {
      // Fallback to default locale
      value = translations[defaultLocale];
      for (const fallbackKey of keys) {
        if (value && typeof value === 'object' && fallbackKey in value) {
          value = value[fallbackKey];
        } else {
          return key; // Return key if translation not found
        }
      }
      break;
    }
  }

  if (typeof value !== 'string') {
    return key;
  }

  // Replace parameters
  let result = value;
  Object.keys(params).forEach((param) => {
    result = result.replace(new RegExp(`{{${param}}}`, 'g'), params[param]);
  });

  return result;
}

// Get locale from URL or browser
export function getLocale(pathname = '') {
  const pathLocale = pathname.split('/')[1];
  if (locales.includes(pathLocale)) {
    return pathLocale;
  }

  if (typeof window !== 'undefined') {
    const browserLocale = navigator.language.split('-')[0];
    if (locales.includes(browserLocale)) {
      return browserLocale;
    }
  }

  return defaultLocale;
}

// Check if locale is RTL
export function isRTL(locale) {
  return locale === 'ar';
}

// Format numbers based on locale
export function formatNumber(number, locale = defaultLocale) {
  if (typeof number !== 'number') return number;

  const localeMap = {
    en: 'en-US',
    fr: 'fr-FR',
    es: 'es-ES',
    de: 'de-DE',
    ar: 'ar-SA',
  };

  return new Intl.NumberFormat(localeMap[locale] || localeMap[defaultLocale]).format(number);
}

// Format dates based on locale
export function formatDate(date, locale = defaultLocale, options = {}) {
  if (!date) return '';

  const localeMap = {
    en: 'en-US',
    fr: 'fr-FR',
    es: 'es-ES',
    de: 'de-DE',
    ar: 'ar-SA',
  };

  const defaultOptions = {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  };

  return new Intl.DateTimeFormat(localeMap[locale] || localeMap[defaultLocale], {
    ...defaultOptions,
    ...options,
  }).format(new Date(date));
}
